(* Shape.v — the trap-free counterpart relative to a STORE SHAPE.

   The contraction theorem (Perbyte.ML_T1_refinement_pb) and the per-byte Stage-2 chain
   (Perbyte.ML_stage2_endtoend_pb) mention no lane geometry, no mask and no PMP table. Geometry enters
   only (a) the generation predicate of Normal_instance.v, whose footprint is fixed to consecutive
   8-byte lanes and which asks for one write for every listed lane, and (b) the PMP conclusion of
   ML_stage2.v, fixed to the same lanes. This file states both relative to a store shape:

     s_lanes        the elements of the instruction;
     s_active       which of them are active (the mask; constant true for an unmasked store);
     s_lo, s_hi     the byte range [s_lo l, s_hi l) of element l.

   It proves
     * `pmp_shape_lanes`: the repaired two-entry table permits the user-mode store of every active
       listed element, from interval facts only (non-empty ranges, pairwise disjoint active ranges,
       background coverage);
     * `gen_shape_pos`: the Stage-2 kernel, with the program order between element writes removed,
       is generated by one execution of a store of this shape (`GenStoreS`), and passes the per-byte
       check at every byte and the main-model check;
     * `stage2_shape`: ONE statement with the conclusions of the per-byte Stage-2 chain, of
       `gen_shape_pos` and of `pmp_shape_lanes`. The normal candidate is built over the ACTIVE
       elements (`act_lanes`): a masked-off element performs no access, so it has no check event.

   Nothing here fixes the shape: s_lanes, s_active, s_lo, s_hi are universally quantified in every
   exported statement. The unit-stride shape and a masked shape are instantiated in
   Shape_instances.v and ML_instance_masked.v.

   0 Admitted / 0 axioms. Modifies no existing .v file. Coq 8.15. *)

