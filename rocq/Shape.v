(* ==================================================================================================
   1. PMP relative to a shape
   ================================================================================================== *)

Section PmpShape.

  Variable Lane : Type.
  Variable lane_eq_dec : forall x y : Lane, {x = y} + {x <> y}.
  Variable s_lanes : list Lane.
  Variable s_active : Lane -> bool.
  Variable s_lo s_hi : Lane -> nat.
  Variable K : Lane.                 (* the designated (faulting, then repaired) element *)
  Variable ram_lo ram_hi : nat.      (* the background region *)

  Hypothesis s_nonempty : forall l, In l s_lanes -> s_lo l < s_hi l.
  Hypothesis s_disjoint : forall l1 l2, In l1 s_lanes -> In l2 s_lanes ->
    s_active l1 = true -> s_active l2 = true -> l1 <> l2 ->
    s_hi l1 <= s_lo l2 \/ s_hi l2 <= s_lo l1.
  Hypothesis K_listed : In K s_lanes.
  Hypothesis K_active : s_active K = true.
  Hypothesis bg_covers : forall l, In l s_lanes -> s_active l = true ->
    ram_lo <= s_lo l /\ s_hi l <= ram_hi.

  (* the repaired entry covers exactly the range of K and grants W; the background entry is the one of
     Frozen_pmp, unchanged by the handler *)
  Definition entry_repaired_s : Frozen_pmp.Entry :=
    {| Frozen_pmp.emode := Frozen_pmp.MNapot; Frozen_pmp.elo := s_lo K; Frozen_pmp.ehi := s_hi K;
       Frozen_pmp.ew := true |}.
  Definition repaired_table_s : list Frozen_pmp.Entry :=
    entry_repaired_s :: Frozen_pmp.entry_background ram_lo ram_hi :: nil.

  Lemma repaired_s_NoM_off : forall l, In l s_lanes -> s_active l = true -> l <> K ->
      Frozen_pmp.matchr entry_repaired_s (s_lo l) (s_hi l) = Frozen_pmp.NoM.
  Proof.
    intros l Hl Ha Hne. apply Frozen_pmp.matchr_NoM_intro; [reflexivity |]. simpl.
    exact (s_disjoint l K Hl K_listed Ha K_active Hne).
  Qed.

  Lemma repaired_s_FullM_K : Frozen_pmp.matchr entry_repaired_s (s_lo K) (s_hi K) = Frozen_pmp.FullM.
  Proof.
    apply Frozen_pmp.matchr_FullM_intro; [reflexivity | exact (s_nonempty K K_listed) | simpl; lia
                                         | simpl; lia].
  Qed.

  Lemma background_s_FullM : forall l, In l s_lanes -> s_active l = true ->
      Frozen_pmp.matchr (Frozen_pmp.entry_background ram_lo ram_hi) (s_lo l) (s_hi l)
      = Frozen_pmp.FullM.
  Proof.
    intros l Hl Ha. destruct (bg_covers l Hl Ha) as [H1 H2].
    apply Frozen_pmp.matchr_FullM_intro; [reflexivity | exact (s_nonempty l Hl) | exact H1 | exact H2].
  Qed.

  (* HEADLINE: every active listed element's user-mode store is allowed by the repaired table. The
     designated element is decided by the repaired entry; every other active element misses it (its
     range is disjoint from K's) and is decided by the background entry. *)
  Theorem pmp_shape_lanes : forall l, In l s_lanes -> s_active l = true ->
      Frozen_pmp.allows repaired_table_s (s_lo l) (s_hi l) Frozen_pmp.PrivU.
  Proof.
    intros l Hl Ha. unfold Frozen_pmp.allows, repaired_table_s.
    destruct (lane_eq_dec l K) as [E | Hne].
    - subst l. rewrite Frozen_pmp.scan_cons_hit by (rewrite repaired_s_FullM_K; discriminate).
      split; [exact repaired_s_FullM_K | reflexivity].
    - rewrite (Frozen_pmp.scan_cons_NoM _ _ _ _ (repaired_s_NoM_off l Hl Ha Hne)).
      rewrite Frozen_pmp.scan_cons_hit by (rewrite (background_s_FullM l Hl Ha); discriminate).
      split; [exact (background_s_FullM l Hl Ha) | reflexivity].
  Qed.

End PmpShape.

(* ==================================================================================================
   2. Generation relative to a shape, and the one-statement counterpart
   ================================================================================================== *)

Section GenShape.

  Variable Event : Type.
  Variable eq_ev_dec : forall x y : Event, {x = y} + {x <> y}.
  Variable Byte Hart Value Lane : Type.
  Variable lane_eq_dec : forall x y : Lane, {x = y} + {x <> y}.
  Variable gmo : Event -> Event -> Prop.
  Variable is_write is_read is_load is_store : Event -> Prop.
  Variable touches : Event -> Byte -> Prop.
  Variable wval : Event -> Byte -> Value.
  Variable same_addr addr data ctrl fence : Event -> Event -> Prop.
  Variable hart : Event -> Hart.
  Variable E0 : list Event.
  Variable rf : Event -> Byte -> Event -> Prop.
  Variable po poloc : Event -> Event -> Prop.
  Variable LS : list (Event * Event).
  Variable Ctx : Event -> Prop.
  Variable ctx_dec : forall e, {Ctx e} + {~ Ctx e}.
  Variable is_chk : Event -> Prop.
  Variable chk_dec : forall e, {is_chk e} + {~ is_chk e}.
  Variable lane : Event -> Lane.
  Variable is_lane_write : Event -> Prop.
  Variable vdata : Lane -> Byte -> Value.
  Variable byte_addr : Byte -> nat.

  (* the shape *)
  Variable s_lanes : list Lane.
  Variable s_active : Lane -> bool.
  Variable s_lo s_hi : Lane -> nat.

  (* the active elements: the normal candidate generates one successful check for each of them *)
  Definition act_lanes : list Lane := filter s_active s_lanes.

  Lemma In_act_lanes : forall l, In l act_lanes <-> In l s_lanes /\ s_active l = true.
  Proof. intro l. unfold act_lanes. apply filter_In. Qed.

  (* ---- the premises of the per-byte Stage-2 chain (Perbyte.ML_stage2_endtoend_pb) ---- *)
  Hypothesis Hirr : forall e, In e E0 -> ~ gmo e e.
  Hypothesis Htr : forall a b c, In a E0 -> In b E0 -> In c E0 -> gmo a b -> gmo b c -> gmo a c.
  Hypothesis Htot : forall a b, In a E0 -> In b E0 -> a <> b -> gmo a b \/ gmo b a.
  Hypothesis Hpo_trans : forall a b c, po a b -> po b c -> po a c.
  Hypothesis Hrf_is_C4 : forall b r w, is_read r -> In r E0 -> rf w b r ->
      L1_abstract_erasure.C4_source Event Byte is_write touches gmo po E0 b r w.
  Hypothesis Hrf_touches : forall w b r, rf w b r -> touches w b.
  Hypothesis Hrf_functional : forall w1 w2 x r, rf w1 x r -> rf w2 x r -> w1 = w2.
  Hypothesis Hlanes : forall k d, In (k, d) LS ->
    ML_T1.LaneOK Event Byte Hart Value gmo is_write is_read touches wval addr data hart E0 rf po k d.
  Hypothesis Hkeeper_survives : forall k d, In (k, d) LS -> ~ ML_base.isdel Event LS k.
  Hypothesis Hfault_pb :
    forall b x, ~ clos_trans Event (CfB Event Byte gmo is_write is_read touches E0 rf poloc b) x x.
  Hypothesis Hfault_main :
    forall x, ~ clos_trans Event
      (Frozen_mainmodel.FRf Event Byte Hart gmo is_write is_read is_load is_store touches
         same_addr addr data ctrl fence hart E0 rf po) x x.
  Hypothesis Hrf_src_write : forall w b r, rf w b r -> is_write w.
  Hypothesis Hrf_tgt_read : forall w b r, rf w b r -> is_read r.
  Hypothesis Hctx_silent :
    forall e, Ctx e -> (~ is_read e) /\ (~ is_write e) /\ (forall b, ~ touches e b).
  Hypothesis Hchk_nonmem :
    forall e, is_chk e -> (~ is_read e) /\ (~ is_write e) /\ (forall b, ~ touches e b).

  Definition E_K := Perbyte.E_K Event eq_ev_dec E0 LS Ctx ctx_dec.
  Definition E_MK := Perbyte.E_MK Event eq_ev_dec E0 LS Ctx ctx_dec is_chk chk_dec.

  (* ---- the shape of the kernel ---- *)
  Hypothesis Hrw : forall e, is_read e -> is_write e -> False.
  Hypothesis Hlane_write_is_write : forall e, is_lane_write e -> is_write e.
  (* one surviving write for every active listed element ... *)
  Hypothesis Hkernel_one_write_per_active :
    forall l, In l s_lanes -> s_active l = true ->
      exists w, In w E_K /\ is_lane_write w /\ lane w = l /\
                (forall w', In w' E_K -> is_lane_write w' -> lane w' = l -> w' = w).
  (* ... and no element write of an inactive or unlisted element *)
  Hypothesis Hkernel_writes_active : forall w, In w E_K -> is_lane_write w ->
    In (lane w) s_lanes /\ s_active (lane w) = true.
  Hypothesis Hfoot : forall e b, In e E_K -> is_lane_write e ->
    (touches e b <-> s_lo (lane e) <= byte_addr b /\ byte_addr b < s_hi (lane e)).
  Hypothesis Hvalue : forall e b, In e E_K -> is_lane_write e -> touches e b ->
    wval e b = vdata (lane e) b.
  Hypothesis Hdeps : forall x a b, In x E_MK -> ~ is_lane_write x ->
    is_lane_write a -> is_lane_write b ->
    (addr x a <-> addr x b) /\ (data x a <-> data x b) /\ (ctrl x a <-> ctrl x b).

  (* ---- generation by one execution of a store of this shape ---- *)
  Record GenStoreS (C : list Event) (poR addrR dataR ctrlR : Event -> Event -> Prop) : Prop := {
    gs_one : forall l, In l s_lanes -> s_active l = true ->
      exists w, In w C /\ is_lane_write w /\ lane w = l /\
                (forall w', In w' C -> is_lane_write w' -> lane w' = l -> w' = w);
    gs_write : forall w, In w C -> is_lane_write w -> is_write w;
    gs_inactive : forall w, In w C -> is_lane_write w ->
      In (lane w) s_lanes /\ s_active (lane w) = true;
    gs_foot : forall w b, In w C -> is_lane_write w ->
      (touches w b <-> s_lo (lane w) <= byte_addr b /\ byte_addr b < s_hi (lane w));
    gs_val : forall w b, In w C -> is_lane_write w -> touches w b -> wval w b = vdata (lane w) b;
    gs_unordered : forall w w', is_lane_write w -> is_lane_write w' -> ~ poR w w';
    gs_position : forall x w w', In x C -> In w C -> In w' C -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' ->
      (poR x w <-> poR x w') /\ (poR w x <-> poR w' x);
    gs_deps : forall x w w', In x C -> ~ is_lane_write x -> is_lane_write w -> is_lane_write w' ->
      (addrR x w <-> addrR x w') /\ (dataR x w <-> dataR x w') /\ (ctrlR x w <-> ctrlR x w')
  }.

  Definition po_G := Normal_instance.po_G Event po is_lane_write.

  Definition Position_before : Prop := forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po x w -> po x w'.
  Definition Position_after : Prop := forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po w x -> po w' x.

  Lemma E_MK_sub_E_K : forall e, In e E_MK -> In e E_K.
  Proof.
    exact (Stage2_normal_candidate.mem_kernel_sub Event E_K is_chk chk_dec).
  Qed.

  Lemma lane_write_in_E_MK : forall e, In e E_K -> is_lane_write e -> In e E_MK.
  Proof.
    intros e H Hl. apply (proj2 (Stage2_normal_candidate.In_mem_kernel_iff Event E_K is_chk chk_dec e)).
    split; [exact H |]. intro Hc. exact (proj1 (proj2 (Hchk_nonmem e Hc)) (Hlane_write_is_write e Hl)).
  Qed.

  Theorem generated_shape : Position_before -> Position_after -> GenStoreS E_MK po_G addr data ctrl.
  Proof.
    intros position_before position_after.
    constructor.
    - intros l Hl Ha. destruct (Hkernel_one_write_per_active l Hl Ha) as [w [Hw [Lw [El U]]]].
      exists w. split; [exact (lane_write_in_E_MK w Hw Lw) |].
      split; [exact Lw |]. split; [exact El |].
      intros w' Hw' Lw' El'. exact (U w' (E_MK_sub_E_K w' Hw') Lw' El').
    - intros w _ Lw. exact (Hlane_write_is_write w Lw).
    - intros w Hw Lw. exact (Hkernel_writes_active w (E_MK_sub_E_K w Hw) Lw).
    - intros w b Hw Lw. exact (Hfoot w b (E_MK_sub_E_K w Hw) Lw).
    - intros w b Hw Lw Tw. exact (Hvalue w b (E_MK_sub_E_K w Hw) Lw Tw).
    - intros w w' Lw Lw' [_ N]. exact (N (conj Lw Lw')).
    - intros x w w' Hx Hw Hw' Nx Lw Lw'. split; split.
      + intros [P _]. split; [exact (position_before x w w' Hx Hw' Nx Lw Lw' P) |].
        intros [L _]; exact (Nx L).
      + intros [P _]. split; [exact (position_before x w' w Hx Hw Nx Lw' Lw P) |].
        intros [L _]; exact (Nx L).
      + intros [P _]. split; [exact (position_after x w w' Hx Hw' Nx Lw Lw' P) |].
        intros [_ L]; exact (Nx L).
      + intros [P _]. split; [exact (position_after x w' w Hx Hw Nx Lw' Lw P) |].
        intros [_ L]; exact (Nx L).
    - intros x w w' Hx Nx Lw Lw'. exact (Hdeps x w w' Hx Nx Lw Lw').
  Qed.

  (* the execution G over the ACTIVE elements, and its two checks *)
  Definition Cn_G_at (b : Byte) :=
    Normal_instance.Cn_G_at Event eq_ev_dec Byte Lane gmo is_write is_read touches E0 rf poloc LS
      Ctx ctx_dec is_chk chk_dec is_lane_write act_lanes b.
  Definition Rn_G :=
    Normal_instance.Rn_G Event eq_ev_dec Byte Hart Lane gmo is_write is_read is_load is_store touches
      same_addr addr data ctrl fence hart E0 rf po LS Ctx ctx_dec is_chk chk_dec is_lane_write act_lanes.

  Theorem gen_shape_pos :
    Position_before -> Position_after ->
    GenStoreS E_MK po_G addr data ctrl
    /\ (forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) (Cn_G_at b) n n)
    /\ (forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) Rn_G n n).
  Proof.
    intros Hb Ha. split; [exact (generated_shape Hb Ha) |]. split.
    - exact (Normal_instance.G_perbyte_acyclic Event eq_ev_dec Byte Hart Value Lane gmo is_write is_read
               touches wval addr data hart E0 rf po poloc LS Ctx ctx_dec is_chk chk_dec is_lane_write
               act_lanes Htot Hrf_touches Hlanes Hfault_pb Hrf_src_write Hrf_tgt_read Hctx_silent
               Hchk_nonmem).
    - exact (Normal_instance.G_mainmodel_acyclic Event eq_ev_dec Byte Hart Value Lane gmo is_write is_read
               is_load is_store touches wval same_addr addr data ctrl fence hart E0 rf po LS Ctx ctx_dec
               is_chk chk_dec is_lane_write act_lanes Htot Hrf_touches Hrf_functional Hlanes
               Hkeeper_survives Hfault_main Hrw Hlane_write_is_write).
  Qed.

  (* ---- the per-byte Stage-2 chain over the active elements, as one Prop ---- *)
  Definition E_C := Perbyte.E_C Event eq_ev_dec E0 LS.
  Definition E_N := Perbyte.E_N Event eq_ev_dec Lane E0 LS Ctx ctx_dec is_chk chk_dec act_lanes.
  Definition rf_C := Perbyte.rf_C Event Byte rf LS.

  Definition Stage2Chain : Prop :=
    ((forall e, In e E_C -> In e E0)
     /\ (forall k d, In (k, d) LS -> ~ In d E_C)
     /\ (forall e, In e E_K -> In e E_C)
     /\ (forall e, In e E_MK -> In e E_K)
     /\ (forall e, In (Stage2_normal_candidate.NKeep Event Lane e) E_N <-> In e E_MK)
     /\ (forall e, In e E_K -> ~ Ctx e))
    /\ L1_abstract_erasure.L1_consistent Event Byte is_write is_read touches gmo po E_C rf_C
    /\ (forall r b w, rf w b r -> exists w', rf_C w' b r /\ wval w' b = wval w b)
    /\ (forall b w_f,
          Obs_final_state.co_max_of Event Byte gmo is_write touches (fun e => In e E0) b w_f ->
          exists w_n,
            Obs_final_state.co_max_of Event Byte gmo is_write touches (fun e => In e E_C) b w_n
            /\ wval w_f b = wval w_n b)
    /\ (forall b x, ~ clos_trans Event
          (Perbyte.Cn_at Event Byte gmo is_write is_read touches rf poloc LS b (fun e => In e E_C)) x x)
    /\ (forall x, ~ clos_trans Event
          (Perbyte.Rn_at Event Byte Hart gmo is_write is_read is_load is_store touches same_addr addr
             data ctrl fence hart E0 rf po LS (fun e => In e E_C)) x x)
    /\ (forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane)
          (Perbyte.Cn_N_at Event eq_ev_dec Byte Lane gmo is_write is_read touches E0 rf poloc LS Ctx
             ctx_dec is_chk chk_dec act_lanes b) n n)
    /\ (forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane)
          (Perbyte.Rn_N Event eq_ev_dec Byte Hart Lane gmo is_write is_read is_load is_store touches
             same_addr addr data ctrl fence hart E0 rf po LS Ctx ctx_dec is_chk chk_dec act_lanes) n n)
    /\ (forall b w,
          Obs_final_state.co_max_of Event Byte gmo is_write touches (fun e => In e E_C) b w
          <-> Obs_final_state.co_max_of (Stage2_normal_candidate.NEv Event Lane) Byte
                (Stage2_normal_candidate.gmo_N Event Lane gmo)
                (Stage2_normal_candidate.is_write_N Event Lane is_write)
                (Stage2_normal_candidate.touches_N Event Byte Lane touches)
                (fun n => In n E_N) b (Stage2_normal_candidate.NKeep Event Lane w)).

  Lemma stage2_chain : Stage2Chain.
  Proof.
    exact (Perbyte.ML_stage2_endtoend_pb Event eq_ev_dec Byte Hart Value Lane gmo is_write is_read
             is_load is_store touches wval same_addr addr data ctrl fence hart E0 rf po poloc LS Ctx
             ctx_dec is_chk chk_dec act_lanes Hirr Htr Htot Hpo_trans Hrf_is_C4 Hrf_touches
             Hrf_functional Hlanes Hkeeper_survives Hfault_pb Hfault_main Hrf_src_write Hrf_tgt_read
             Hctx_silent Hchk_nonmem).
  Qed.

  (* the normal candidate has a check event exactly for the active listed elements *)
  Lemma E_N_checks_active : forall l,
      In (Stage2_normal_candidate.NChk Event Lane l) E_N <-> In l s_lanes /\ s_active l = true.
  Proof.
    intro l. rewrite <- In_act_lanes. unfold E_N, Perbyte.E_N, Stage2_normal_candidate.EN'.
    rewrite in_app_iff. split.
    - intros [H | H].
      + apply in_map_iff in H. destruct H as [x [Hx _]]. discriminate Hx.
      + apply in_map_iff in H. destruct H as [x [Hx Hin]]. inversion Hx; subst. exact Hin.
    - intro H. right. apply in_map. exact H.
  Qed.

  (* ---- the PMP part, over the same shape ---- *)
  Variable K : Lane.
  Variable ram_lo ram_hi : nat.
  Hypothesis s_nonempty : forall l, In l s_lanes -> s_lo l < s_hi l.
  Hypothesis s_disjoint : forall l1 l2, In l1 s_lanes -> In l2 s_lanes ->
    s_active l1 = true -> s_active l2 = true -> l1 <> l2 ->
    s_hi l1 <= s_lo l2 \/ s_hi l2 <= s_lo l1.
  Hypothesis K_listed : In K s_lanes.
  Hypothesis K_active : s_active K = true.
  Hypothesis bg_covers : forall l, In l s_lanes -> s_active l = true ->
    ram_lo <= s_lo l /\ s_hi l <= ram_hi.

  (* HEADLINE: the trap-free counterpart relative to a store shape, as one statement *)
  Theorem stage2_shape :
    Position_before -> Position_after ->
    Stage2Chain
    /\ (forall l, In (Stage2_normal_candidate.NChk Event Lane l) E_N <->
                  In l s_lanes /\ s_active l = true)
    /\ GenStoreS E_MK po_G addr data ctrl
    /\ (forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) (Cn_G_at b) n n)
    /\ (forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) Rn_G n n)
    /\ (forall l, In l s_lanes -> s_active l = true ->
          Frozen_pmp.allows (repaired_table_s Lane s_lo s_hi K ram_lo ram_hi) (s_lo l) (s_hi l)
            Frozen_pmp.PrivU).
  Proof.
    intros Hb Ha.
    split; [exact stage2_chain |].
    split; [exact E_N_checks_active |].
    destruct (gen_shape_pos Hb Ha) as [G1 [G2 G3]].
    split; [exact G1 |]. split; [exact G2 |]. split; [exact G3 |].
    exact (pmp_shape_lanes Lane lane_eq_dec s_lanes s_active s_lo s_hi K ram_lo ram_hi s_nonempty
             s_disjoint K_listed K_active bg_covers).
  Qed.

End GenShape.
